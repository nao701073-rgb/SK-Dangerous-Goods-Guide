import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const checks=[];const check=(name,pass,detail='')=>checks.push({name,pass:Boolean(pass),detail});
const exists=p=>fs.existsSync(path.join(root,p));
const text=p=>fs.readFileSync(path.join(root,p),'utf8');
const catalog=JSON.parse(text('data/publication-rights-catalog.json'));
check('権利・公開範囲台帳が存在する',exists('data/publication-rights-catalog.json'));
check('台帳にコンテンツ資産が登録されている',catalog.summary.total>=600,`${catalog.summary.total}件`);
check('IMDG等のライセンス確認対象を識別している',(catalog.summary.byClass['licensed-international-code']||0)>0,`${catalog.summary.byClass['licensed-international-code']||0}件`);
check('国内法令の表示資産を識別している',(catalog.summary.byClass['official-domestic-law']||0)>0,`${catalog.summary.byClass['official-domestic-law']||0}件`);
check('高リスク未確認資産を識別している',(catalog.summary.byRisk.high||0)>0,`${catalog.summary.byRisk.high||0}件`);
check('公開範囲ポリシーが存在する',exists('data/publication-scope-policy.js'));
check('権利・公開範囲管理画面が存在する',exists('pages/publication-rights-admin.html'));
check('表示ゲートが存在する',exists('assets/js/publication-scope-gate.js'));
check('管理画面JSが存在する',exists('assets/js/publication-rights-admin.js'));
check('DBマイグレーションが存在する',exists('server/sql/097_part509_copyright_publication_scope.sql'));
check('公開用サニタイズビルドが存在する',exists('server/scripts/build-public-sanitized-package.js'));
const sql=text('server/sql/097_part509_copyright_publication_scope.sql');
check('権利確認者と承認者の分離制約がある',sql.includes('reviewed_by <> prepared_by')&&sql.includes('approved_by <> reviewed_by'));
check('外部公開・社内公開・権限者限定の範囲がある',sql.includes('public-approved')&&sql.includes('internal-authenticated')&&sql.includes('internal-restricted'));
check('書誌情報のみ・外部リンクのみ・遮断を扱える',sql.includes('metadata-only')&&sql.includes('external-link-only')&&sql.includes('blocked'));
const server=text('server/src/server.js');
check('サーバー側公開範囲APIがある',server.includes('/api/admin/publication-scope')&&server.includes('/api/publication-rights/items'));
check('外部公開の権利状態確認APIがある',server.includes('/api/public/publication-rights-status'));
const gate=text('assets/js/publication-scope-gate.js');
check('公開範囲ゲートが直接リンクを判定する',gate.includes('publication-rights-status')&&gate.includes('blocked'));
const failed=checks.filter(x=>!x.pass);
const report={release:'part509',phase:3,title:'著作権・社内公開範囲の確認',generatedAt:new Date().toISOString(),checks:{total:checks.length,passed:checks.length-failed.length,failed:failed.length},results:checks,status:failed.length?'failed':'passed'};
const out=path.join(root,'docs/part509_第3段階静的検証レポート.json');fs.writeFileSync(out,JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));process.exit(failed.length?1:0);
