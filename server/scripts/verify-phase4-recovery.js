import fs from 'fs';
import path from 'path';
const root=path.resolve(new URL('../..',import.meta.url).pathname);
const exists=p=>fs.existsSync(path.join(root,p));
const text=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];const check=(name,ok,detail='')=>checks.push({name,passed:Boolean(ok),detail});
check('DBマイグレーションが存在する',exists('server/sql/098_part510_backup_restore_migration_drill.sql'));
const sql=text('server/sql/098_part510_backup_restore_migration_drill.sql');
check('復旧設定テーブル',sql.includes('system_recovery_settings'));
check('復旧訓練テーブル',sql.includes('system_recovery_drills'));
check('リリース切替履歴',sql.includes('system_release_activations'));
for(const file of ['create-release-package.sh','verify-release-package.sh','restore-drill.sh','migration-drill.sh','activate-release.sh','rollback-release.sh','backup.sh','restore.sh','verify-backup.sh','integrity-check.sh'])check(`${file} が存在する`,exists(`server/scripts/${file}`));
const backup=text('server/scripts/backup.sh');
check('DBカスタム形式バックアップ',backup.includes('pg_dump')&&backup.includes('--format=custom'));
check('システムリリースをバックアップ対象に含む',backup.includes('create-release-package.sh'));
check('秘密情報をリリース対象外にする',text('server/scripts/create-release-package.sh').includes('server/.env'));
check('復元前バックアップ',text('server/scripts/restore.sh').includes('RESTORE_SKIP_PRE_BACKUP'));
check('復元確認文字列',text('server/scripts/restore.sh').includes('RESTORE_CONFIRMATION'));
check('隔離復元訓練',text('server/scripts/restore-drill.sh').includes('createdb')&&text('server/scripts/restore-drill.sh').includes('dropdb'));
check('原子的な切替',text('server/scripts/activate-release.sh').includes('mv -Tf'));
check('ヘルスチェック失敗時ロールバック',text('server/scripts/activate-release.sh').includes('Health check failed; rolled back'));
check('第4段階管理画面',exists('pages/recovery-migration-admin.html'));
check('第4段階APIクライアント',exists('assets/js/recovery-migration-admin.js'));
check('第4段階CSS',exists('assets/css/recovery-phase4.css'));
const server=text('server/src/server.js');
check('復旧準備API',server.includes('/api/admin/recovery/readiness'));
check('復旧設定API',server.includes('/api/admin/recovery/settings'));
check('復旧訓練API',server.includes('/api/admin/recovery/drills'));
const failed=checks.filter(x=>!x.passed);
const report={release:'part510',phase:4,title:'バックアップ・復元・移行試験',generatedAt:new Date().toISOString(),checks:{total:checks.length,passed:checks.length-failed.length,failed:failed.length},results:checks,status:failed.length?'failed':'passed'};
const out=path.join(root,'docs/part510_第4段階静的検証レポート.json');fs.writeFileSync(out,JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));process.exit(failed.length?1:0);
